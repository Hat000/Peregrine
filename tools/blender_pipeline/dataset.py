"""Write a YOLO-pose dataset (images + labels) from sampled poses through a Renderer.

Label format is the ultralytics YOLO-pose row the deployed ``racer.vision.detector`` /
``racer.vision.synthetic`` already use -- so a model trained on THIS data is a drop-in:

    class cx cy w h (x y v)*4        (all normalized to [0,1])

  * class       : 0 = "gate" (single class).
  * cx cy w h   : bbox centre + size, normalized by image W/H.
  * (x y v)*4   : the 4 inner-square corners in IPPE_SQUARE order (0=LL,1=LR,2=UR,3=UL),
                  x/y normalized + clamped to [0,1], v in {2 visible, 1 occluded, 0 off-frame}.
  * kpt_shape   : [4, 3]   flip_idx: [1, 0, 3, 2]   (see data.yaml).

We REUSE ``racer.vision.synthetic.to_yolo_pose_label`` for the row formatting (one source of
truth for normalization + visibility), wrapping our ProjectedGate in a minimal sample shim so
the on-disk rows are byte-identical to the synthetic generator's. Layout:

    out_dir/
      data.yaml
      images/{train,val}/frame_000000.jpg
      labels/{train,val}/frame_000000.txt
      meta.jsonl                 # one json line per frame: pose params + label (provenance)

NB this 4-keypoint label is the deployed PnP set (the gate OPENING). The blender_gen photoreal
pipeline emits an 8-keypoint superset (inner-4 + outer-4); the detector subsets to the inner 4
at the model boundary, so a 4-kpt model trained here is compatible. Documented in APPEARANCE_SPEC.
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass

import numpy as np

from racer.frames import IMAGE_HEIGHT, IMAGE_WIDTH
from racer.vision.synthetic import to_yolo_pose_label

from .appearance import AppearanceParams, load_appearance
from .camera_sampler import CameraPose, SamplerConfig, sample_poses
from .projector import N_CORNERS, ProjectedGate, project_gate

try:
    import cv2
except Exception as exc:  # pragma: no cover
    cv2 = None
    _CV2_ERR = exc


DATA_YAML = """\
# VQ2 'Now You See Me' gate dataset for YOLO-pose (ultralytics).
# Generated by tools/blender_pipeline (Blender-free harness; mock or Blender renderer).
path: {path}
train: images/train
val: images/val
names:
  0: gate
kpt_shape: [4, 3]        # 4 inner-square corners, (x, y, visibility)
flip_idx: [1, 0, 3, 2]   # horizontal flip swaps left<->right corners
"""


@dataclass
class _LabelSample:
    """Minimal shim with the fields ``to_yolo_pose_label`` reads, so we reuse its formatting."""

    bbox_xywh: np.ndarray
    keypoints_px: np.ndarray
    visibility: np.ndarray
    visible: bool


def yolo_pose_row(proj: ProjectedGate, class_id: int = 0) -> str | None:
    """Format one ProjectedGate as a YOLO-pose label row (or None if unusable), reusing the
    canonical ``synthetic.to_yolo_pose_label`` so rows match the synthetic generator bit-for-bit.

    'usable' = in front of the camera with >= 3 corners in frame (the detector's pose-recoverable
    floor; matches synthetic's ``visible`` criterion)."""
    usable = proj.in_front and proj.n_visible >= 3
    shim = _LabelSample(
        bbox_xywh=proj.bbox_xywh,
        keypoints_px=proj.corners_px,
        visibility=proj.visibility,
        visible=usable,
    )
    return to_yolo_pose_label(shim, class_id=class_id)


def _ensure_dirs(out_dir: str) -> None:
    for sub in ("images/train", "images/val", "labels/train", "labels/val"):
        os.makedirs(os.path.join(out_dir, sub), exist_ok=True)


def write_dataset(out_dir: str, renderer, n_train: int, n_val: int, *,
                  seed: int = 0, cfg: SamplerConfig | None = None,
                  params: AppearanceParams | None = None,
                  inner_size_m: float | None = None) -> dict:
    """Sample poses, render each through ``renderer``, and write images + YOLO-pose labels.

    ``renderer`` is any object with ``render(pose, params) -> HxWx3 BGR`` (the MockRenderer now,
    a Blender renderer later). Returns a summary dict (counts + the data.yaml path). Frames whose
    label is unusable (gate behind camera / < 3 corners) are still rendered + written with an
    EMPTY label file (a valid YOLO negative), and counted under ``n_negative``.
    """
    if cv2 is None:  # pragma: no cover
        raise RuntimeError(f"write_dataset requires OpenCV (cv2): {_CV2_ERR}")
    cfg = cfg or SamplerConfig()
    params = params or load_appearance()
    inner = inner_size_m if inner_size_m is not None else cfg.inner_size_m
    _ensure_dirs(out_dir)

    with open(os.path.join(out_dir, "data.yaml"), "w") as f:
        f.write(DATA_YAML.format(path=os.path.abspath(out_dir)))

    meta_path = os.path.join(out_dir, "meta.jsonl")
    summary = {"n_train": 0, "n_val": 0, "n_negative": 0, "data_yaml": os.path.join(out_dir, "data.yaml")}
    with open(meta_path, "w") as meta:
        for split, n in (("train", n_train), ("val", n_val)):
            poses = sample_poses(n, seed=seed + (0 if split == "train" else 10_000),
                                 cfg=cfg, visible_only=True)
            for i, pose in enumerate(poses):
                img = renderer.render(pose, params)
                proj = project_gate(pose.R_cam_gate, pose.t_cam_gate, inner)
                stem = f"frame_{i:06d}"
                img_path = os.path.join(out_dir, "images", split, stem + ".jpg")
                lbl_path = os.path.join(out_dir, "labels", split, stem + ".txt")
                cv2.imwrite(img_path, img)
                row = None if proj is None else yolo_pose_row(proj)
                with open(lbl_path, "w") as lf:
                    lf.write((row + "\n") if row else "")
                if row is None:
                    summary["n_negative"] += 1
                summary[f"n_{split}"] += 1
                meta.write(json.dumps({
                    "split": split, "stem": stem, "image": os.path.relpath(img_path, out_dir),
                    "range_m": pose.range_m, "bearing_deg": pose.bearing_deg,
                    "elevation_deg": pose.elevation_deg, "gate_yaw_deg": pose.gate_yaw_deg,
                    "gate_pitch_deg": pose.gate_pitch_deg, "gate_roll_deg": pose.gate_roll_deg,
                    "label": row,
                }) + "\n")
    summary["meta"] = meta_path
    return summary
